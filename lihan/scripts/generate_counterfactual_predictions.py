"""Runs the real graph pipeline against each story's counterfactual variant --
this has never been done before this script; generate_real_predictions.py
only ever loads the "original" variant (see its load_story call). This gives
H2 (the memorization gap: does the model do worse on a surface-perturbed but
structurally identical passage?) its first real data point.

Requires web/src/data/predictions/story_XX.json (the original-variant
results, already generated by generate_real_predictions.py) to exist for the
memorization-gap comparison. Output:
web/src/data/predictions/story_XX_counterfactual.json.

Provider is selectable via LLM_PROVIDER=featherless|groq (default
featherless, requires FEATHERLESS_API_KEY, model override FEATHERLESS_MODEL)
or LLM_PROVIDER=groq (free tier, requires GROQ_API_KEY, model override
GROQ_MODEL) -- see generate_real_predictions.py's docstring for why.
"""

import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)

from pipeline.llm_client import FeatherlessLLMClient, GroqLLMClient
from pipeline.graph_pipeline import run_graph_pipeline
from metrics.awt_f1 import awt_f1, memorization_gap, scored_edges

STORIES_DIR = os.path.join(ROOT, "data", "stories")
OUT_DIR = os.path.join(ROOT, "web", "src", "data", "predictions")

PROVIDER = os.environ.get("LLM_PROVIDER", "featherless")
if PROVIDER == "groq":
    CLIENT_CLASS = GroqLLMClient
    MODEL = os.environ.get("GROQ_MODEL", "openai/gpt-oss-120b")
else:
    CLIENT_CLASS = FeatherlessLLMClient
    MODEL = os.environ.get("FEATHERLESS_MODEL", "Qwen/Qwen2.5-72B-Instruct")


def load_story(story_dir, variant):
    path = os.path.join(STORIES_DIR, story_dir, f"{variant}.json")
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def passage_from_story(story):
    by_id = {e["id"]: e for e in story["events"]}
    ordered_ids = sorted(by_id, key=lambda i: int(i[1:]))
    return [by_id[i]["text"] for i in ordered_ids]



def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(STORIES_DIR, "manifest.json"), encoding="utf-8") as f:
        manifest = json.load(f)["stories"]

    only = os.environ.get("ONLY_STORIES")
    if only:
        wanted = set(only.split(","))
        manifest = [entry for entry in manifest if entry["id"] in wanted]

    for entry in manifest:
        story = load_story(entry["dir"], "counterfactual")
        passage = passage_from_story(story)
        print(f"-- {entry['id']} counterfactual ({len(story['events'])} events) --", flush=True)

        client = CLIENT_CLASS(model=MODEL)
        result = run_graph_pipeline(passage, client)
        result["model"] = MODEL

        scores = awt_f1(story, result)
        result["scored_edges"] = scored_edges(story["edges"], result["edges"], result.get("global_order"))
        result["awt_f1_scores"] = scores

        out_path = os.path.join(OUT_DIR, f"{entry['dir']}_counterfactual.json")
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(result, f, indent=2)

        original_path = os.path.join(OUT_DIR, f"{entry['dir']}.json")
        gap_line = ""
        if os.path.exists(original_path):
            with open(original_path, encoding="utf-8") as f:
                original_result = json.load(f)
            if "awt_f1_scores" in original_result:
                gap = memorization_gap(original_result["awt_f1_scores"], scores)
                result["memorization_gap"] = gap
                with open(out_path, "w", encoding="utf-8") as f:
                    json.dump(result, f, indent=2)
                gap_line = f" | memorization_gap(awt_f1)={gap['awt_f1']:+.3f}"

        print(f"{entry['id']}: awt_f1={scores['awt_f1']:.3f} "
              f"(relation={scores['relation_score']:.3f}, "
              f"thread={scores['thread_attribution_accuracy']:.3f}, "
              f"convergence={scores['convergence_f1']:.3f})"
              f"{gap_line} -> {out_path}")


if __name__ == "__main__":
    main()
